"""
Unified LLM Engine for Legal Document Drafting.
Supports Google Gemini, OpenAI, Groq/OpenRouter, and an Offline Mock Engine.
Includes strict token telemetry and cost estimation.
"""

import time
import os
from dataclasses import dataclass
from typing import List, Dict, Any, Optional
from config import MODEL_PRICING, USD_TO_INR
from core.prompts import MASTER_LEGAL_SYSTEM_PROMPT


@dataclass
class TokenUsage:
    prompt_tokens: int
    completion_tokens: int
    total_tokens: int
    cost_usd: float
    cost_inr: float
    latency_sec: float
    model: str


@dataclass
class LLMResponse:
    content: str
    usage: TokenUsage
    raw_response: Optional[Any] = None


def calculate_cost(model: str, prompt_tokens: int, completion_tokens: int) -> tuple[float, float]:
    """Calculate estimated cost in USD and INR."""
    pricing = MODEL_PRICING.get(model, {"input": 0.15, "output": 0.60})
    cost_usd = (prompt_tokens * pricing["input"] / 1_000_000) + (
        completion_tokens * pricing["output"] / 1_000_000
    )
    cost_inr = cost_usd * USD_TO_INR
    return cost_usd, cost_inr


def call_llm(
    messages: List[Dict[str, str]],
    model: str = "gemini-2.5-flash",
    api_key: Optional[str] = None,
    temperature: float = 0.2,
    base_url: Optional[str] = None
) -> LLMResponse:
    """
    Unified entry point to call Gemini, OpenAI, or Mock Engine with token telemetry.
    """
    start_time = time.time()
    
    # 1. Fallback to Mock Engine if explicitly selected or if no API key is provided
    if model == "mock-offline-engine" or not api_key:
        return _mock_legal_engine(messages, model, start_time)

    # 2. Google Gemini Models
    if "gemini" in model.lower():
        return _call_gemini(messages, model, api_key, temperature, start_time)

    # 3. OpenAI or OpenAI-compatible (Groq / OpenRouter)
    return _call_openai_compatible(messages, model, api_key, temperature, base_url, start_time)


def _call_gemini(
    messages: List[Dict[str, str]],
    model: str,
    api_key: str,
    temperature: float,
    start_time: float
) -> LLMResponse:
    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=api_key)
        
        system_instruction = MASTER_LEGAL_SYSTEM_PROMPT
        
        gemini_contents = []
        for msg in messages:
            role = "user" if msg["role"] == "user" else "model"
            gemini_contents.append(
                types.Content(
                    role=role,
                    parts=[types.Part.from_text(text=msg["content"])]
                )
            )

        config = types.GenerateContentConfig(
            system_instruction=system_instruction,
            temperature=temperature,
        )

        # Fast candidate list for Gemini
        candidate_models = ["gemini-3.8-flash", "gemini-2.5-flash"]
        if model and model not in candidate_models:
            candidate_models.insert(0, model)

        response = None
        used_model = model
        last_error = None

        for candidate in candidate_models:
            try:
                response = client.models.generate_content(
                    model=candidate,
                    contents=gemini_contents,
                    config=config,
                )
                used_model = candidate
                break
            except Exception as ex:
                last_error = ex
                continue

        # If Google cloud is experiencing high demand across all candidates,
        # seamlessly fallback to the built-in statutory legal engine so user is never blocked!
        if response is None:
            fallback_resp = _mock_legal_engine(messages, "gemini-fallback", start_time)
            notice = "*(ℹ️ Google Gemini servers are currently experiencing temporary high demand; your draft has been seamlessly generated by the LexCraft statutory engine below.)*\n\n"
            fallback_resp.content = notice + fallback_resp.content
            return fallback_resp

        latency = time.time() - start_time
        
        prompt_tokens = 0
        completion_tokens = 0
        total_tokens = 0
        
        if hasattr(response, "usage_metadata") and response.usage_metadata:
            prompt_tokens = response.usage_metadata.prompt_token_count or 0
            completion_tokens = response.usage_metadata.candidates_token_count or 0
            total_tokens = response.usage_metadata.total_token_count or (prompt_tokens + completion_tokens)
        else:
            prompt_tokens = sum(len(m["content"].split()) * 4 // 3 for m in messages) + 1200
            completion_tokens = len(response.text.split()) * 4 // 3
            total_tokens = prompt_tokens + completion_tokens

        cost_usd, cost_inr = calculate_cost(used_model, prompt_tokens, completion_tokens)
        
        usage = TokenUsage(
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            cost_usd=cost_usd,
            cost_inr=cost_inr,
            latency_sec=round(latency, 2),
            model=used_model
        )

        return LLMResponse(content=response.text, usage=usage, raw_response=response)

    except Exception as e:
        # Graceful fallback to verified legal templates on any unexpected connection error
        fallback_resp = _mock_legal_engine(messages, "gemini-fallback", start_time)
        notice = f"*(ℹ️ Note: Live API encountered: `{str(e)[:80]}`. Switched to offline legal engine to fulfill your request.)*\n\n"
        fallback_resp.content = notice + fallback_resp.content
        return fallback_resp


def _call_openai_compatible(
    messages: List[Dict[str, str]],
    model: str,
    api_key: str,
    temperature: float,
    base_url: Optional[str],
    start_time: float
) -> LLMResponse:
    try:
        from openai import OpenAI

        client_kwargs = {"api_key": api_key, "timeout": 20.0}
        if base_url:
            client_kwargs["base_url"] = base_url

        client = OpenAI(**client_kwargs)

        formatted_messages = [{"role": "system", "content": MASTER_LEGAL_SYSTEM_PROMPT}]
        for msg in messages:
            formatted_messages.append({"role": msg["role"], "content": msg["content"]})

        # Candidates to try in order on Groq (llama-3.1-8b-instant is guaranteed available on free tier)
        candidate_models = ["llama-3.1-8b-instant", "llama3-8b-8192", "mixtral-8x7b-32768", "llama-3.3-70b-versatile"]
        if model and model not in candidate_models:
            candidate_models.insert(0, model)

        response = None
        used_model = model
        last_error = None

        for candidate in candidate_models:
            try:
                response = client.chat.completions.create(
                    model=candidate,
                    messages=formatted_messages,
                    temperature=temperature
                )
                used_model = candidate
                break
            except Exception as ex:
                last_error = ex
                continue

        if response is None:
            # Fallback to statutory engine if all models fail
            fallback_resp = _mock_legal_engine(messages, "offline-fallback", start_time)
            notice = "*(ℹ️ Cloud API models temporarily unavailable; draft generated using LexCraft statutory engine.)*\n\n"
            fallback_resp.content = notice + fallback_resp.content
            return fallback_resp

        latency = time.time() - start_time
        content = response.choices[0].message.content or ""

        prompt_tokens = response.usage.prompt_tokens if response.usage else 0
        completion_tokens = response.usage.completion_tokens if response.usage else 0
        total_tokens = response.usage.total_tokens if response.usage else (prompt_tokens + completion_tokens)

        cost_usd, cost_inr = calculate_cost(used_model, prompt_tokens, completion_tokens)

        usage = TokenUsage(
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            cost_usd=cost_usd,
            cost_inr=cost_inr,
            latency_sec=round(latency, 2),
            model=used_model
        )

        return LLMResponse(content=content, usage=usage, raw_response=response)

    except Exception as e:
        # Graceful fallback on any connection issue
        fallback_resp = _mock_legal_engine(messages, "offline-fallback", start_time)
        notice = f"*(ℹ️ Notice: Live API returned `{str(e)[:70]}`. To keep your work moving, draft was fulfilled using the statutory engine below.)*\n\n"
        fallback_resp.content = notice + fallback_resp.content
        return fallback_resp


